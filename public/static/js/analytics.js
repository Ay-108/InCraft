/* =========================================
   InCraft — Analytics JavaScript
   static/js/analytics.js

   Analytics Dashboard
   Dark + Orange Theme
   ========================================= */


document.addEventListener("DOMContentLoaded", async function () {
    if (window.InCraftChartReady) {
        await window.InCraftChartReady;
    }


    /* =========================================
       1. ANALYTICS DATA
       ========================================= */

    const analyticsDataElement =
        document.getElementById("analyticsData");


    /*
     * Read JSON safely from the data-* attributes
     * generated by Flask/Jinja.
     */

    function readJSON(attributeName, fallback = []) {

        if (!analyticsDataElement) {
            return fallback;
        }

        const rawValue =
            analyticsDataElement.dataset[attributeName];

        if (!rawValue) {
            return fallback;
        }

        try {

            const parsedValue =
                JSON.parse(rawValue);

            return Array.isArray(parsedValue)
                ? parsedValue
                : fallback;

        } catch (error) {

            console.error(
                `Unable to parse analytics data: ${attributeName}`,
                error
            );

            return fallback;
        }
    }


    /*
     * Real data supplied by Flask.
     */

    const revenueLabels =
        readJSON("revenueLabels");


    const revenueData =
        readJSON("revenueValues")
            .map(function (value) {
                return Number(value) || 0;
            });


    const categoryLabels =
        readJSON("categoryLabels");


    const categoryData =
        readJSON("categoryValues")
            .map(function (value) {
                return Number(value) || 0;
            });


    const topProductLabels =
        readJSON("topProductLabels");


    const topProductData =
        readJSON("topProductValues")
            .map(function (value) {
                return Number(value) || 0;
            });


    /*
     * Inventory health is calculated from the
     * low-stock product information currently
     * available on the Analytics page.
     *
     * The backend does not currently provide a
     * separate inventory-health dataset through
     * #analyticsData.
     */

    // Inventory health comes directly from the same active-products query
    // used by Dashboard, not from the low-stock rows currently visible on screen.
    const healthyStock =
        Number(analyticsDataElement?.dataset.stockIn || 0);

    const lowStock =
        Number(analyticsDataElement?.dataset.stockLow || 0);

    const outOfStock =
        Number(analyticsDataElement?.dataset.stockOut || 0);

    const totalStockProducts =
        Number(analyticsDataElement?.dataset.stockTotal || 0);

    const inventoryLabels = [
        "Healthy",
        "Low Stock",
        "Out of Stock"
    ];

    const inventoryData = [
        healthyStock,
        lowStock,
        outOfStock
    ];


    /* =========================================
       2. CHART DEFAULTS
       ========================================= */

    if (typeof Chart !== "undefined") {

        Chart.defaults.font.family =
            "Inter, Arial, sans-serif";

        Chart.defaults.font.size = 11;

        Chart.defaults.color =
            "#777777";

        Chart.defaults.borderColor =
            "#E5E5E5";
    }


    /* =========================================
       3. REVENUE CHART
       ========================================= */

    const revenueCanvas =
        document.getElementById("revenueChart");


    if (
        revenueCanvas &&
        typeof Chart !== "undefined"
    ) {

        new Chart(
            revenueCanvas,
            {

                type: "line",

                data: {

                    labels: revenueLabels,

                    datasets: [

                        {

                            label: "Revenue",

                            data: revenueData,

                            borderColor:
                                "#F47521",

                            backgroundColor:
                                "rgba(244, 117, 33, 0.10)",

                            borderWidth: 2.5,

                            fill: true,

                            tension: 0.4,

                            pointRadius: 3,

                            pointHoverRadius: 6,

                            pointBackgroundColor:
                                "#F47521",

                            pointBorderColor:
                                "#F47521"

                        }

                    ]

                },


                options: {

                    responsive: true,

                    maintainAspectRatio: false,

                    interaction: {

                        intersect: false,

                        mode: "index"

                    },


                    plugins: {

                        legend: {

                            display: false

                        },


                        tooltip: {

                            backgroundColor:
                                "#171717",

                            titleColor:
                                "#FFFFFF",

                            bodyColor:
                                "#D0D0D0",

                            borderColor:
                                "rgba(244, 117, 33, 0.38)",

                            borderWidth: 1,

                            padding: 10,

                            displayColors: false,


                            callbacks: {

                                label: function (context) {

                                    const value =
                                        Number(
                                            context.raw || 0
                                        );


                                    return (
                                        "Revenue: ₹" +
                                        value.toLocaleString(
                                            "en-IN"
                                        )
                                    );

                                }

                            }

                        }

                    },


                    scales: {

                        x: {

                            grid: {

                                display: false

                            },

                            ticks: {

                                color:
                                    "#777777"

                            }

                        },


                        y: {

                            beginAtZero: true,

                            grid: {

                                color:
                                    "rgba(229, 229, 229, 0.85)"

                            },

                            ticks: {

                                color:
                                    "#777777",


                                callback:
                                    function (value) {

                                        return (
                                            "₹" +
                                            Number(value)
                                                .toLocaleString(
                                                    "en-IN"
                                                )
                                        );

                                    }

                            }

                        }

                    }

                }

            }
        );

    }


    /* =========================================
       4. CATEGORY SALES CHART
       ========================================= */

    const categoryCanvas =
        document.getElementById(
            "categorySalesChart"
        );


    if (
        categoryCanvas &&
        typeof Chart !== "undefined"
    ) {

        new Chart(
            categoryCanvas,
            {

                type: "doughnut",

                data: {

                    labels: categoryLabels,

                    datasets: [

                        {

                            data: categoryData,

                            backgroundColor: [

                                "#F47521",
                                "#23252B",
                                "#777777",
                                "#A3A3A3",
                                "#C7C7C7"

                            ],

                            borderWidth: 2,

                            borderColor:
                                "#171717"

                        }

                    ]

                },


                options: {

                    responsive: true,

                    maintainAspectRatio: false,

                    cutout: "65%",


                    plugins: {

                        legend: {

                            display: true,

                            position: "bottom",


                            labels: {

                                color:
                                    "#777777",

                                padding: 14,

                                boxWidth: 10,

                                boxHeight: 10,

                                usePointStyle: true,

                                font: {

                                    size: 10

                                }

                            }

                        },


                        tooltip: {

                            backgroundColor:
                                "#171717",

                            titleColor:
                                "#FFFFFF",

                            bodyColor:
                                "#D0D0D0",

                            borderColor:
                                "rgba(244, 117, 33, 0.38)",

                            borderWidth: 1,

                            padding: 10

                        }

                    }

                }

            }
        );

    }


    /* =========================================
       5. TOP PRODUCTS CHART
       ========================================= */

    const topProductsCanvas =
        document.getElementById(
            "topProductsChart"
        );


    if (
        topProductsCanvas &&
        typeof Chart !== "undefined"
    ) {

        new Chart(
            topProductsCanvas,
            {

                type: "bar",

                data: {

                    labels: topProductLabels,

                    datasets: [

                        {

                            label: "Units Sold",

                            data: topProductData,

                            backgroundColor:
                                "#F47521",

                            borderRadius: 6,

                            borderSkipped: false,

                            barThickness: "flex",

                            maxBarThickness: 42

                        }

                    ]

                },


                options: {

                    indexAxis: "y",

                    responsive: true,

                    maintainAspectRatio: false,


                    plugins: {

                        legend: {

                            display: false

                        },


                        tooltip: {

                            backgroundColor:
                                "#171717",

                            titleColor:
                                "#FFFFFF",

                            bodyColor:
                                "#D0D0D0",

                            borderColor:
                                "rgba(244, 117, 33, 0.38)",

                            borderWidth: 1,

                            padding: 10,


                            callbacks: {

                                label: function (context) {

                                    return (
                                        "Units Sold: " +
                                        Number(
                                            context.raw || 0
                                        ).toLocaleString(
                                            "en-IN"
                                        )
                                    );

                                }

                            }

                        }

                    },


                    scales: {

                        x: {

                            beginAtZero: true,

                            grid: {

                                color:
                                    "rgba(229, 229, 229, 0.85)"

                            },

                            ticks: {

                                color:
                                    "#777777"

                            }

                        },


                        y: {

                            grid: {

                                display: false

                            },

                            ticks: {

                                color:
                                    "#777777"

                            }

                        }

                    }

                }

            }
        );

    }


    /* =========================================
       6. INVENTORY HEALTH CHART
       ========================================= */

    const inventoryCanvas =
        document.getElementById(
            "inventoryHealthChart"
        );


    if (
        inventoryCanvas &&
        typeof Chart !== "undefined"
    ) {

        new Chart(
            inventoryCanvas,
            {

                type: "doughnut",

                data: {

                    labels: inventoryLabels,

                    datasets: [

                        {

                            data: inventoryData,

                            backgroundColor: [

                                "#22C55E",
                                "#F59E0B",
                                "#EF4444"

                            ],

                            borderWidth: 2,

                            borderColor:
                                "#171717"

                        }

                    ]

                },


                options: {

                    responsive: true,

                    maintainAspectRatio: false,

                    cutout: "65%",


                    plugins: {

                        legend: {

                            display: true,

                            position: "bottom",


                            labels: {

                                color:
                                    "#777777",

                                padding: 14,

                                boxWidth: 10,

                                boxHeight: 10,

                                usePointStyle: true,

                                font: {

                                    size: 10

                                }

                            }

                        },


                        tooltip: {

                            backgroundColor:
                                "#171717",

                            titleColor:
                                "#FFFFFF",

                            bodyColor:
                                "#D0D0D0",

                            borderColor:
                                "rgba(244, 117, 33, 0.38)",

                            borderWidth: 1,

                            padding: 10

                        }

                    }

                }

            }
        );

    }


    /* =========================================
       7. DATE FILTER
       ========================================= */

    const analyticsDate =
        document.getElementById("analyticsDate");

    const applyAnalyticsFilters =
        document.getElementById("applyAnalyticsFilters");

    function applyAnalyticsPeriod() {
        if (!analyticsDate) return;

        const selectedRange = ["3", "6", "12"].includes(analyticsDate.value)
            ? analyticsDate.value
            : "6";

        const destination = new URL(window.location.href);
        destination.searchParams.set("months", selectedRange);
        window.location.assign(destination.toString());
    }

    if (analyticsDate) {
        analyticsDate.addEventListener("change", applyAnalyticsPeriod);
    }

    if (applyAnalyticsFilters) {
        applyAnalyticsFilters.addEventListener("click", applyAnalyticsPeriod);
    }


    /* =========================================
       8. KPI NUMBER FORMATTING
       ========================================= */

    const kpiValues =
        document.querySelectorAll(
            "[data-kpi]"
        );


    kpiValues.forEach(
        function (element) {

            const value =
                Number(
                    element.dataset.kpi
                );


            if (Number.isNaN(value)) {

                return;

            }


            element.textContent =
                value.toLocaleString(
                    "en-IN"
                );

        }
    );


    /* =========================================
       9. REVENUE FORMATTING
       ========================================= */

    const revenueValues =
        document.querySelectorAll(
            "[data-revenue]"
        );


    revenueValues.forEach(
        function (element) {

            const value =
                Number(
                    element.dataset.revenue
                );


            if (Number.isNaN(value)) {

                return;

            }


            element.textContent =
                "₹" +
                value.toLocaleString(
                    "en-IN",
                    {

                        minimumFractionDigits: 0,

                        maximumFractionDigits: 0

                    }
                );

        }
    );


    /* =========================================
       10. EXPORT REPORT
       ========================================= */

    const exportReportBtn =
        document.getElementById(
            "exportReportBtn"
        );


    if (exportReportBtn) {

        exportReportBtn.addEventListener(
            "click",
            function () {

                /*
                 * Current export action creates a
                 * printable Analytics report.
                 *
                 * This does not require a backend
                 * route change.
                 */

                window.print();

            }
        );

    }


    // Explicit chart states prevent empty datasets from looking like broken charts.
    function setChartNote(elementId, message) {
        const note = document.getElementById(elementId);
        if (note) note.textContent = message;
    }

    if (typeof Chart === "undefined") {
        setChartNote("revenueChartNote", "Chart.js could not be loaded. Check your network connection and refresh.");
        setChartNote("categoryChartNote", "Chart.js could not be loaded. Check your network connection and refresh.");
        setChartNote("topProductsChartNote", "Chart.js could not be loaded. Check your network connection and refresh.");
        setChartNote("inventoryHealthChartNote", "Chart.js could not be loaded. Check your network connection and refresh.");
    } else {
        if (!revenueData.some(function (value) { return value > 0; })) {
            setChartNote("revenueChartNote", "No sales revenue is recorded in the selected period. The trend will populate when sales are recorded.");
        }

        if (!categoryData.some(function (value) { return value > 0; })) {
            setChartNote("categoryChartNote", "No category sales are recorded in the selected period.");
        }

        if (!topProductData.some(function (value) { return value > 0; })) {
            setChartNote("topProductsChartNote", "No product sales are recorded in the selected period.");
        }

        if (totalStockProducts === 0) {
            setChartNote("inventoryHealthChartNote", "No active inventory products are available to chart.");
        }
    }


    /* =========================================
       11. ANALYTICS READY STATE
       ========================================= */

    document.body.classList.add(
        "analytics-ready"
    );


});